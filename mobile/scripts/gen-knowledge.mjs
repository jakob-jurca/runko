// Generates platform/knowledge-files.js: the /knowledge Markdown bundle that
// Vite builds with import.meta.glob on the web. Keys mimic the glob's paths.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const here = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(here, '..', '..', 'knowledge')

function bundle(sub) {
  const dir = path.join(root, sub)
  const out = {}
  for (const f of readdirSync(dir).filter((n) => n.endsWith('.md')).sort()) {
    const key = `../../knowledge/${sub ? sub + '/' : ''}${f}`
    out[key] = readFileSync(path.join(dir, f), 'utf8')
  }
  return out
}

const src = `// GENERATED by scripts/gen-knowledge.mjs — do not edit, do not commit.
export const RAW_FILES = ${JSON.stringify(bundle(''), null, 0)}
export const RESEARCH_FILES = ${JSON.stringify(bundle('research'), null, 0)}
`
writeFileSync(path.join(here, '..', 'platform', 'knowledge-files.js'), src)
console.log('knowledge bundle written')
